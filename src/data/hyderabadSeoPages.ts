export function findSeoPageBySlug(rawSlug: string): HyderabadSeoPage | undefined {
  const clean = rawSlug.replace(/^\/+/, '').replace(/\/+$/, '').toLowerCase().trim();
  return HYDERABAD_SEO_PAGES.find((p) => p.slug.toLowerCase() === clean);
}

export function getRelatedServicesForArea(area: string, currentSlug: string): HyderabadSeoPage[] {
  return HYDERABAD_SEO_PAGES.filter(
    (p) => p.area.toLowerCase() === area.toLowerCase() && p.slug.toLowerCase() !== currentSlug.toLowerCase()
  ).slice(0, 4);
}

export function getNearbyAreaPagesForService(service: string, area: string, currentSlug: string): HyderabadSeoPage[] {
  const page = findSeoPageBySlug(currentSlug);
  const nearby = page?.nearbyAreas || [];
  return HYDERABAD_SEO_PAGES.filter(
    (p) => p.service.toLowerCase() === service.toLowerCase() && nearby.includes(p.area) && p.slug !== currentSlug
  ).slice(0, 4);
}
